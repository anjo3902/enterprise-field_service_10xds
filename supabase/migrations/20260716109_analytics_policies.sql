DROP POLICY IF EXISTS "kpi_snap_select" ON public.kpi_snapshots;
CREATE POLICY "kpi_snap_select" ON public.kpi_snapshots FOR SELECT USING (
  public.fn_is_platform_admin()
  OR org_id = public.fn_jwt_org_id()
  OR vendor_id = public.fn_jwt_vendor_id()
  OR technician_id = public.fn_jwt_tech_id()
);
-- Snapshots are generated by Edge Functions (service_role)
DROP POLICY IF EXISTS "kpi_snap_write" ON public.kpi_snapshots;
CREATE POLICY "kpi_snap_write" ON public.kpi_snapshots FOR ALL USING (public.fn_is_platform_admin());

