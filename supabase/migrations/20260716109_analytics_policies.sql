CREATE POLICY "dashboard_snap_select" ON public.dashboard_snapshots FOR SELECT USING (
  public.fn_is_platform_admin()
  OR (dashboard_type = 'organization' AND entity_id = public.fn_jwt_org_id())
  OR (dashboard_type = 'vendor' AND entity_id = public.fn_jwt_vendor_id())
  OR (dashboard_type = 'technician' AND entity_id = public.fn_jwt_tech_id())
);
DROP POLICY IF EXISTS "dashboard_snap_write" ON public.dashboard_snapshots;
CREATE POLICY "dashboard_snap_write" ON public.dashboard_snapshots FOR ALL USING (public.fn_is_platform_admin());

